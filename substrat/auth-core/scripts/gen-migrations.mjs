#!/usr/bin/env node
// Bundle @authhero/drizzle's SQL migrations into a generated module, so the
// worker can apply them against a freshly-minted tenant store at
// /internal/provision (the K-31 ready-gate) — Workers have no filesystem, so
// `migrationsFolder` approaches don't apply. Reads the drizzle journal for
// order; statements are split on drizzle's `--> statement-breakpoint` marker.
import { readFileSync, writeFileSync, existsSync, realpathSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
// Resolve through the workspace symlink (the package's exports map doesn't
// expose package.json, so require.resolve can't be used here).
const drizzlePkg = realpathSync(join(here, "..", "node_modules", "@authhero", "drizzle"));
const migrationsDir = join(drizzlePkg, "drizzle");
const journalPath = join(migrationsDir, "meta", "_journal.json");
const outFile = join(here, "..", "src", "migrations.generated.ts");

if (!existsSync(journalPath)) {
  console.error(`gen-migrations: no journal at ${journalPath}`);
  process.exit(2);
}

const journal = JSON.parse(readFileSync(journalPath, "utf8"));
const entries = [];
for (const e of journal.entries) {
  const sql = readFileSync(join(migrationsDir, `${e.tag}.sql`), "utf8");
  entries.push({ tag: e.tag, sql });
}

const body = entries
  .map((e) => `  { tag: ${JSON.stringify(e.tag)}, sql: ${JSON.stringify(e.sql)} },`)
  .join("\n");

const next = `// GENERATED by scripts/gen-migrations.mjs from @authhero/drizzle/drizzle — DO NOT EDIT, do not commit.
export interface BundledMigration { tag: string; sql: string; }
export const MIGRATIONS: BundledMigration[] = [
${body}
];
`;

const prev = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;
if (prev === next) {
  console.log(`gen-migrations: ${entries.length} migration(s) unchanged`);
} else {
  writeFileSync(outFile, next);
  console.log(`gen-migrations: wrote ${entries.length} migration(s) → src/migrations.generated.ts`);
}
